"""Write `jobs/<experiment>/job.py` and `jobs/<experiment>/README.md` from the table.

    python scripts/generate_jobs.py
    python scripts/generate_jobs.py --check      # fail if anything is stale

GENERATED, NOT WRITTEN
----------------------
Nine job folders differing along three axes is exactly the shape of thing that
drifts. Generating them from `config/experiments.py` means a change to the protocol
cannot leave a stale README behind saying the old number of rounds, and cannot leave
job 7 using a hyperparameter job 6 stopped using.

`--check` is the guard: it regenerates into memory and compares, so a job file edited
by hand is detected rather than silently kept. Run it before submitting.

WHAT A job.py IS ALLOWED TO CONTAIN
-----------------------------------
Its own experiment id, and nothing else. No hyperparameters, no model definition, no
partition geometry. If a job file contained any of those, the nine would begin
disagreeing on day one — which is precisely how this project once ended up with a
server building a ResNet-18 while its clients built a ResNet-50.
"""

